class CacheCandidates(unittest.TestCase):
    def test_stage_sequence_preserves_other_features_and_reverses_wiring(self):
        root = Path("/server")
        original = server_config(root)
        path = root / ".local/cache/redis_password"
        off = prep.cache_model(original, "off", path)
        self.assertEqual(off["services"]["api"]["environment"]["TASKFLOW_CACHE_ENABLED"], "false")
        self.assertNotIn(prep.NETWORK, off["networks"])
        connected = prep.cache_model(off, "connect", path)
        enabled = prep.cache_model(connected, "enable", path)
        self.assertEqual(enabled["services"]["api"]["environment"]["TASKFLOW_CACHE_ENABLED"], "true")
        disabled = prep.cache_model(enabled, "off", path)
        self.assertIn(prep.NETWORK, disabled["services"]["api"]["networks"])
        detached = prep.cache_model(disabled, "detach", path)
        self.assertEqual(detached, off)
        for model in (off, connected, enabled, disabled, detached):
            prep.validate_server(model)
            self.assertEqual(set(model["services"]), {"postgres", "migrate", "api", "web"})
            for name in ("postgres", "migrate", "web"):
                self.assertEqual(model["services"][name], original["services"][name])
            self.assertEqual(model["volumes"], original["volumes"])
            for key, value in original["services"]["api"]["environment"].items():
                self.assertEqual(model["services"]["api"]["environment"][key], value)
            for key, value in original["services"]["api"]["networks"].items():
                self.assertEqual(model["services"]["api"]["networks"][key], value)
        self.assertNotIn("TASKFLOW_CACHE_ENABLED", original["services"]["api"]["environment"])
        with self.assertRaisesRegex(RuntimeError, "before enabling"):
            prep.cache_model(original, "enable", path)

    def test_refuses_conflicting_or_shared_wiring(self):
        root = Path("/server")
        path = root / ".local/cache/redis_password"
        cases = []
        data = server_config(root); data["networks"][prep.NETWORK] = {"external": True, "name": "other-redis"}; cases.append(data)
        data = server_config(root); data["secrets"][prep.SECRET] = {"file": "/other/password"}; cases.append(data)
        data = server_config(root); data["services"]["web"]["networks"][prep.NETWORK] = {}; cases.append(data)
        data = server_config(root); data["services"]["migrate"]["secrets"].append({"source": prep.SECRET}); cases.append(data)
        data = server_config(root); data["services"]["api"]["secrets"].append({"source": "app_url", "target": "/run/secrets/redis_password"}); cases.append(data)
        for data in cases:
            for mode in prep.MODES:
                with self.assertRaises(RuntimeError): prep.cache_model(data, mode, path)

    def test_compose_autogenerated_fields_survive_roundtrip(self):
        root = Path('/server')
        path = root / '.local/cache/redis_password'
        connected = prep.cache_model(server_config(root), 'connect', path)
        # Real Compose adds these fields when a JSON candidate is normalized.
        connected['networks'][prep.NETWORK]['ipam'] = {}
        connected['secrets'][prep.SECRET]['name'] = 'taskflow-server_redis_password'
        enabled = prep.cache_model(connected, 'enable', path)
        self.assertEqual(enabled['services']['api']['environment']['TASKFLOW_CACHE_ENABLED'], 'true')
        detached = prep.cache_model(enabled, 'detach', path)
        self.assertNotIn(prep.NETWORK, detached['networks'])
        self.assertNotIn(prep.SECRET, detached['secrets'])

    def test_rejects_wrong_server_boundary(self):
        for change in ("services", "ip", "ports", "origin"):
            data = server_config(Path("/server"))
            if change == "services": data["services"]["redis"] = {}
            if change == "ip": data["services"]["api"]["networks"]["edge"]["ipv4_address"] = "172.30.23.4"
            if change == "ports": data["services"]["api"]["ports"] = [{"published": "9090"}]
            if change == "origin": data["services"]["api"]["environment"]["TASKFLOW_PUBLIC_ORIGIN"] = "https://other.example"
            with self.assertRaises(RuntimeError): prep.validate_server(data)

    def test_only_new_files_stale_and_tampered_candidates_fail(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            base = root / "compose.server.yaml"
            base.write_text("current source")
            original = server_config(root)
            init_cache.prepare(root / ".local/cache")
            credentials = {p.name: p.read_bytes() for p in (root / ".local/cache").iterdir()}
            with patch.object(prep, "normalized", return_value=original):
                first = prep.prepare("connect", root)
                second = prep.prepare("connect", root)
                self.assertNotEqual(first, second)
                self.assertEqual(base.read_text(), "current source")
                self.assertEqual(prep.check(first, root), json.loads((first / "candidate.json").read_text()))
                for path in first.iterdir(): self.assertEqual(path.stat().st_mode & 0o777, 0o600)
                self.assertEqual(first.stat().st_mode & 0o777, 0o700)
                candidate = json.loads((first / "candidate.json").read_text())
                candidate["services"]["api"]["image"] = "unreviewed-image"
                (first / "candidate.json").write_text(json.dumps(candidate))
                with self.assertRaisesRegex(RuntimeError, "unexpected changes"): prep.check(first, root)
                base.write_text("new CD release")
                with self.assertRaisesRegex(RuntimeError, "stale"): prep.check(second, root)
            self.assertEqual(credentials, {p.name: p.read_bytes() for p in (root / ".local/cache").iterdir()})

    def test_env_change_pending_and_bad_acl_fail_without_overwrite(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "compose.server.yaml").write_text("source")
            data = server_config(root)
            with patch.object(prep, "normalized", return_value=data):
                directory = prep.prepare("off", root)  # off does not need Redis files
                changed = copy.deepcopy(data)
                changed["services"]["api"]["environment"]["DISCORD_APPLICATION_ID"] = "changed"
                with patch.object(prep, "normalized", return_value=changed):
                    with self.assertRaisesRegex(RuntimeError, "stale"): prep.check(directory, root)
                init_cache.prepare(root / ".local/cache")
                (root / ".local/cache/users.acl").write_text("user default on nopass +@all\n")
                with self.assertRaisesRegex(RuntimeError, "ACL"): prep.prepare("connect", root)
                prep.prepare("detach", root)  # emergency detach ignores Redis files
                pending = root / ".local/deploy/cd/pending.json"
                pending.parent.mkdir(parents=True)
                pending.write_text("{}")
                with self.assertRaisesRegex(RuntimeError, "Unfinished"): prep.prepare("off", root)


